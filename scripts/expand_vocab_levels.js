// Helper to append unique by 'word'
function appendVocab(filePath, newItems, idPrefix) {
  const existing = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  const seenWords = new Set(existing.map(x => x.word.trim().toLowerCase()));
  let count = existing.length;

  for (const item of newItems) {
    if (!seenWords.has(item.word.trim().toLowerCase())) {
      count++;
      const id = `${idPrefix}_${String(count).padStart(4, '0')}`;
      existing.push({
        id,
        ...item
      });
      seenWords.add(item.word.trim().toLowerCase());
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(existing, null, 2), 'utf-8');
  console.log(`Updated ${path.basename(filePath)}: now ${existing.length} items.`);
}

